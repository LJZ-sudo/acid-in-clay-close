export function ValidationRecipeBlock() {
  const recipe = useStageOutputLoader(STUDIO_FILES.validationRecipeSpace, { kindHint: 'json' })
  const stab = useStageOutputLoader(STUDIO_FILES.researchPriorityRankStability, { kindHint: 'json' })
  const top10 = useStageOutputLoader(STUDIO_FILES.researchPriorityTop10, { kindHint: 'json' })

  if (recipe.loading) return <p className="text-xs text-gray-500">Loading…</p>
  if (recipe.result?.status !== 'ok') {
    return (
      <StudioEmpty
        title="validation_recipe_space.json unavailable"
        detail="Recipe space is produced within the selected validation branch. If this file is missing, Stage B recipe completion may not have run yet."
      />
    )
  }

  const d = recipe.result.data
  const selected = d.selected_recipe ?? d.recipe ?? d.primary_recipe ?? d
  const modules = d.modules ?? d.recipe_modules ?? selected?.modules
  const rationale = d.rationale ?? d.selection_rationale ?? selected?.rationale ?? d.why_this_recipe
  const rankStab = stab.result?.status === 'ok' ? stab.result.data : null
  const topOk = top10.result?.status === 'ok' ? top10.result.data : null
  const topCount = topOk
    ? Array.isArray(topOk.candidates)
      ? topOk.candidates.length
      : Array.isArray(topOk.top_10)
        ? topOk.top_10.length
        : Array.isArray(topOk)
          ? topOk.length
          : null
    : null

  return (
    <div className="space-y-3 text-sm">
      <p className="text-xs text-gray-600">
        Recipe content is scoped to the selected validation branch. It is not presented as a cross-study &quot;AI global
        winner&quot;.
      </p>
      <div className="rounded-lg border p-3 bg-white">
        <h4 className="text-xs font-semibold text-gray-800">Recipe within branch</h4>
        <pre className="text-xs mt-2 whitespace-pre-wrap max-h-56 overflow-auto font-sans">{typeof selected === 'string' ? selected : JSON.stringify(selected, null, 2)}</pre>
      </div>
      {modules && (
        <div>
          <h4 className="text-xs font-semibold mb-1">Modules</h4>
          <pre className="text-xs bg-gray-50 p-2 rounded whitespace-pre-wrap max-h-40 overflow-auto">{JSON.stringify(modules, null, 2)}</pre>
        </div>
      )}
      {rationale && (
        <p className="text-xs text-gray-700">
          <span className="font-semibold">Why this recipe (in-branch):</span>{' '}
          {typeof rationale === 'string' ? rationale : JSON.stringify(rationale)}
        </p>
      )}
      {rankStab && (
        <details className="text-xs border rounded p-2">
          <summary className="cursor-pointer font-semibold">Rank stability (research_priority_rank_stability.json)</summary>
          <pre className="mt-2 max-h-36 overflow-auto whitespace-pre-wrap">{JSON.stringify(rankStab, null, 2)}</pre>
        </details>
      )}
      {topCount != null && (
        <p className="text-[11px] text-gray-500">
          Optional cross-check: <code className="text-[10px] bg-gray-100 px-1 rounded">research_priority_top10_candidates.json</code>{' '}
          lists {topCount} ranked row(s) in the current file snapshot (for context, not a performance leaderboard).
        </p>
      )}
    </div>
  )
}

